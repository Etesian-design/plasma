// Generates the Plasma colour schemes from the etesian-design tokens (src/styles/tokens.css), so the desktop and the
// Storybook designs share one source. Usage: node --experimental-strip-types scripts/colors.ts [path/to/design-repo]
// Writes look/colors/Etesian.colors (hybrid: light pages, dark chrome, like the phone) and look/colors/EtesianDark.colors.

import { writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { type RGB, type Tokens, root, hybrid, dark, rgb, over, mix } from './tokens.ts'

const kde = (c: RGB) => c.join(',')

const accent = rgb(root['color-accent-default'])
const negative = rgb(root['color-palette-warning'])
const neutral = rgb(root['color-palette-attention'])
const positive: RGB = [0x1b, 0xa5, 0x48] // the Chats green; the tokens have no positive colour yet

/** One [Colors:*] group: a background, its text colours and the shared accent/state colours. */
function group(bg: RGB, alt: RGB, t: Tokens) {
  const fg = rgb(t['c-fg'])
  return {
    BackgroundNormal: kde(bg), BackgroundAlternate: kde(alt),
    ForegroundNormal: kde(fg), ForegroundInactive: kde(rgb(t['c-fg-secondary'])), ForegroundActive: kde(accent),
    ForegroundLink: kde(rgb(t['c-link'])), ForegroundVisited: kde(mix(rgb(t['c-link']), fg, 0.35)),
    ForegroundNegative: kde(negative), ForegroundNeutral: kde(neutral), ForegroundPositive: kde(positive),
    DecorationFocus: kde(accent), DecorationHover: kde(accent),
  }
}

/** A scheme: `page` tokens for windows and views, `chrome` tokens for title bars, headers and panels. */
function scheme(name: string, page: Tokens, chrome: Tokens) {
  const bg = rgb(page['c-bg']), surface = rgb(page['c-surface'])
  const button = rgb(page['c-button-bg'])
  // The chrome is a gradient (toolbar-from -> toolbar-to); a flat colour takes its middle.
  const bar = mix(rgb(chrome['c-toolbar-from']), rgb(chrome['c-toolbar-to']), 0.5)
  const barInactive = mix(bar, rgb(chrome['c-bg']), 0.12)
  const overlay = rgb('#141414')
  const groups: Record<string, Record<string, string>> = {
    'Colors:Window': group(bg, rgb(page['c-surface-raised']), page),
    'Colors:View': group(surface, rgb(page['c-surface-raised']), page),
    'Colors:Button': group(button, over(button, page['c-pressed']), page),
    'Colors:Selection': { ...group(accent, mix(accent, bg, 0.3), { ...page, 'c-fg': '#FFFFFF', 'c-fg-secondary': '#E6EEFF' }), ForegroundActive: '255,255,255' },
    'Colors:Tooltip': group(overlay, overlay, dark),
    'Colors:Complementary': group(rgb(dark['c-surface']), rgb(dark['c-surface-raised']), dark),
    'Colors:Header': group(bar, bar, chrome),
    'Colors:Header][Inactive': group(barInactive, barInactive, { ...chrome, 'c-fg': chrome['c-fg-secondary'] }),
  }
  const lines = [
    '# Generated by scripts/colors.ts from etesian-design tokens.css; do not edit by hand.',
    '[General]', `ColorScheme=${name.replace(/ /g, '')}`, `Name=${name}`, 'shadeSortColumn=true', '',
    '[KDE]', 'contrast=4', '',
  ]
  for (const [g, kv] of Object.entries(groups)) lines.push(`[${g}]`, ...Object.entries(kv).map(([k, v]) => `${k}=${v}`), '')
  lines.push('[WM]',
    `activeBackground=${kde(bar)}`, `activeForeground=${kde(rgb(chrome['c-fg']))}`, `activeBlend=${kde(bar)}`,
    `inactiveBackground=${kde(barInactive)}`, `inactiveForeground=${kde(rgb(chrome['c-fg-secondary']))}`, `inactiveBlend=${kde(barInactive)}`, '')
  return lines.join('\n')
}

const out = join(import.meta.dirname, '../look/colors')
mkdirSync(out, { recursive: true })
// Hybrid: the phone's default, light pages under dark chrome. Dark: everything dark.
writeFileSync(join(out, 'Etesian.colors'), scheme('Etesian', hybrid, dark))
writeFileSync(join(out, 'EtesianDark.colors'), scheme('Etesian Dark', dark, dark))
console.log('wrote', out)
